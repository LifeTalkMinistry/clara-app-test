function fill(template, config) {
  return String(template || "").replace(/\{(\w+)\}/g, (_, key) => config?.[key] || "");
}

function getTodayKey(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function hashString(value) {
  let hash = 2166136261;
  const text = String(value || "");
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function getFirstSignalKey(bank = {}) {
  return Object.keys(bank)[0] || null;
}

function pickTemplatePair(stageKey, signalId, mode) {
  const openers = mode === "guidance" ? GUIDANCE_OPENERS : AWARENESS_OPENERS;
  const contexts = mode === "guidance" ? GUIDANCE_CONTEXTS : AWARENESS_CONTEXTS;
  const count = openers.length * contexts.length;
  const comboIndex = hashString(`${stageKey}|${signalId}|${mode}|${getTodayKey()}`) % count;
  const opener = openers[comboIndex % openers.length];
  const context = contexts[Math.floor(comboIndex / openers.length) % contexts.length];
  return [opener, context];
}

export function getRotatingSignalCopy(stageKey, signalId, mode = "awareness") {
  const normalizedStage = normalizeLifeStageKey(stageKey);
  const normalizedMode = mode === "guidance" ? "guidance" : "awareness";
  const bank = LIFE_STAGE_SIGNAL_COPY_BANKS[normalizedStage];
  if (!bank) return null;

  const fallbackKey = getFirstSignalKey(bank);
  const config = bank[signalId] || bank[fallbackKey];
  if (!config) return null;

  const [opener, context] = pickTemplatePair(normalizedStage, signalId || fallbackKey, normalizedMode);

  return {
    title: normalizedMode === "guidance" ? config.guidanceTitle : config.awarenessTitle,
    body: `${fill(opener, config)} ${fill(context, config)}`.replace(/\s+/g, " ").trim(),
  };
}

export function getSignalRotationCount(stageKey, signalId) {
  const normalizedStage = normalizeLifeStageKey(stageKey);
  const bank = LIFE_STAGE_SIGNAL_COPY_BANKS[normalizedStage];
  const config = bank?.[signalId];
  if (!config) return { awareness: 0, guidance: 0 };

  return {
    awareness: AWARENESS_OPENERS.length * AWARENESS_CONTEXTS.length,
    guidance: GUIDANCE_OPENERS.length * GUIDANCE_CONTEXTS.length,
  };
}

export default getRotatingSignalCopy;
