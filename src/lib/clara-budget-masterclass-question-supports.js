export function getBudgetMasterclassQuestionSupports(language = "en", stepId = "", questionIndex = 0) {
  const code = ["en", "tl", "es"].includes(String(language || "").toLowerCase())
    ? String(language).toLowerCase()
    : "en";
  const group = BUDGET_MASTERCLASS_QUESTION_SUPPORTS[String(stepId || "")] || {};
  const items = group[code] || group.en || [];
  const index = Math.max(0, Number(questionIndex) || 0);
  const item = items[index];
  return item ? { ...item } : null;
}
